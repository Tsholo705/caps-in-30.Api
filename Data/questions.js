// Simple helper used by the services layer.
export function filterQuestions(grade, subject, topic) {
    return QUESTIONS.filter(function (q) {
        if (q.grade !== grade) return false;
        if (subject && q.subject !== subject) return false;
        if (topic && topic !== "All Topics" && q.topic !== topic) return false;
        return true;
    });
}
